const { chromium } = require('playwright')
const sheet = p => p.locator('div[style*="max-width: 520px"]').last()
;(async()=>{
  const b=await chromium.launch(); const errs=[]
  const p=await b.newPage({viewport:{width:390,height:1500}}); p.on('pageerror',e=>errs.push(e.message))
  const db = () => p.evaluate(()=>JSON.parse(JSON.stringify(window.__db)))
  await p.goto('http://127.0.0.1:8765/'); await p.waitForTimeout(300)
  const T = await p.evaluate(()=>window.__T), TM = await p.evaluate(()=>window.__add(1))
  console.log('舊紀錄冷卻（10天前 還沒興趣 → +30）:', await p.evaluate(()=>window.__cool({date:window.__add(-10), note:'邀了沒約成：還沒興趣　她說再看看'})), '應為', await p.evaluate(()=>window.__add(20)))
  console.log('舊紀錄沒原因（7天）:', await p.evaluate(()=>window.__cool({date:window.__add(-1), note:'邀了沒約成'})), '應為', await p.evaluate(()=>window.__add(6)))
  await p.evaluate(()=>window.__nav('/contacts/w1')); await p.waitForTimeout(1500)
  let t = await p.textContent('#root'); console.log('他的頁面 下一次卡:', /還沒約下一次/.test(t), ' 按鈕記一次邀約:', /記一次邀約/.test(t), ' 沒有定時間:', !/定時間/.test(t))
  await p.getByRole('button',{name:'記一次邀約'}).first().click(); await p.waitForTimeout(500)
  let s = sheet(p); await s.getByRole('button',{name:'見面聊聊'}).click(); await s.getByRole('button',{name:'沒約成'}).click(); await p.waitForTimeout(100)
  await p.screenshot({path:'s18a.png'})
  await s.getByRole('button',{name:'還在等回覆'}).click()
  await s.getByRole('button',{name:'記下來'}).click(); await p.waitForTimeout(1200)
  let d = await db(); console.log('等回覆:', JSON.stringify(d.contact_logs.filter(l=>l.contact_id==='w1'&&l.kind==='invite_wait').map(l=>[l.date===T?'今天':l.date,l.note])))
  t = await p.textContent('#root'); console.log('互動紀錄顯示:', t.includes('邀了，等回覆：見面聊聊'), ' 旁邊有約成了:', t.includes('約成了'))
  await p.screenshot({path:'s18b.png'})
  await p.getByRole('button',{name:'約成了'}).first().click(); await p.waitForTimeout(500)
  s = sheet(p); let st = await s.textContent(); console.log('標題:', st.slice(0,14))
  await s.getByRole('button',{name:'選日期'}).last().click(); await p.waitForTimeout(300)
  await p.getByRole('button',{name:String(Number(TM.slice(8,10))),exact:true}).last().click(); await p.waitForTimeout(300)
  await sheet(p).locator('input[type=time]').fill('15:00')
  await sheet(p).getByRole('button',{name:'記下來'}).click(); await p.waitForTimeout(1500)
  d = await db()
  console.log('改成約成:', JSON.stringify(d.contact_logs.filter(l=>l.contact_id==='w1'&&l.date===T&&l.kind).map(l=>[l.kind,l.note])), ' 沒多一筆等回覆:', !d.contact_logs.some(l=>l.contact_id==='w1'&&l.kind==='invite_wait'))
  console.log('約會:', JSON.stringify(d.counter_logs.filter(r=>r.contact_id==='w1').map(r=>[r.date===T?'今天':r.date, r.planned_date===TM?'明天':r.planned_date, r.note])))
  t = await p.textContent('#root'); console.log('下一次卡:', (t.match(/下一次.{0,20}/)||[])[0])
  console.log('今天 3-1-2 邀約數 （contact_logs 今天 ask）:', d.contact_logs.filter(l=>l.date===T&&['meet_plan','invite_no','invite_wait'].includes(l.kind)).length)
  await p.evaluate(()=>window.__nav('/report')); await p.waitForTimeout(1800)
  t = await p.textContent('#root'); console.log('報告:', (t.match(/開口邀約裡：[^前]{0,80}/)||[])[0])
  console.log('ERR', errs.slice(0,5)); await b.close()
})()
