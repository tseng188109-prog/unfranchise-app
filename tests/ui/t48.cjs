// 新增／編輯互動名單：居住地區打字跳建議、同名或同 IG 提醒、兩台裝置同時改
const { chromium, devices } = require('playwright')
let fail = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fail = 1 }
;(async () => {
  const b = await chromium.launch(); const errs = []
  const c = await b.newContext({ ...devices['iPhone 14'] }); const p = await c.newPage(); p.on('pageerror', e => errs.push(e.message))
  await p.goto('http://127.0.0.1:8766/'); await p.waitForTimeout(400)
  await p.evaluate(() => { const c1 = window.__db.contacts.find(c => c.id === 'c1'); Object.assign(c1, { platform: 'IG', platform_account: 'wang_yq', region: '新加坡' }) })
  const go = async x => { await p.evaluate(x => window.__nav(x), x); await p.waitForTimeout(1200) }
  const text = () => p.evaluate(() => document.body.innerText)
  await go('/contacts/new')
  // 同名
  await p.getByPlaceholder('輸入姓名...').fill('王怡茜'); await p.waitForTimeout(400)
  ok((await text()).includes('互動名單裡已經有一位「王怡茜」，請確認是不是同一個人。'), '同名：提醒已經有一位')
  await p.getByPlaceholder('輸入姓名...').fill('王小明'); await p.waitForTimeout(300)
  ok(!(await text()).includes('互動名單裡已經有'), '不同名：沒有提醒')
  // 同 IG
  await p.getByRole('button', { name: 'IG', exact: true }).click()
  await p.getByPlaceholder('帳號名稱，例如 abc_123').fill('@Wang_YQ'); await p.waitForTimeout(400)
  ok((await text()).includes('互動名單裡的「王怡茜」也是這個帳號，請確認是不是同一個人。'), '同 IG 帳號（大小寫、@ 不一樣）：提醒是王怡茜')
  await p.screenshot({ path: __dirname + '/shots/t48_dup.png' })
  // 地區建議
  await p.getByRole('button', { name: /展開更多/ }).click(); await p.waitForTimeout(300)
  const region = p.getByPlaceholder('例：台北市大安區')
  await region.fill('大安'); await p.waitForTimeout(300)
  const sug = p.getByRole('listbox', { name: '地區建議' })
  ok((await sug.innerText()).includes('台北市大安區') && (await sug.innerText()).includes('台中市大安區'), '打「大安」：跳出台北市、台中市的大安區')
  await p.screenshot({ path: __dirname + '/shots/t48_region.png' })
  await sug.getByRole('button', { name: '台北市大安區' }).click(); await p.waitForTimeout(300)
  ok((await region.inputValue()) === '台北市大安區' && !(await sug.isVisible().catch(() => false)), '點一下就填好，建議收起來')
  await region.fill('新'); await p.waitForTimeout(400)
  ok((await sug.innerText()).split('\n')[0].includes('新加坡') && (await sug.innerText()).includes('你打過的'), '自己打過的「新加坡」排最前面，標「你打過的」')
  await region.fill('日本東京'); await p.waitForTimeout(300)
  ok(!(await sug.isVisible().catch(() => false)) && (await region.inputValue()) === '日本東京', '國外沒有建議，照打')
  await p.getByRole('button', { name: '儲存並返回' }).click(); await p.waitForTimeout(800)
  const ins = await p.evaluate(() => window.__ops.filter(o => o[0] === 'insert' && o[1] === 'contacts').map(o => o[2]))
  ok(ins.length === 1 && ins[0].region === '日本東京', '存起來的是打的「日本東京」')

  // ── 編輯：兩台裝置同時改 ──
  await go('/contacts/c1/edit')
  await p.getByRole('button', { name: /展開更多|更多資料/ }).first().click().catch(() => {})
  await p.waitForTimeout(300)
  // 另一台改了地區
  await p.evaluate(() => { window.__db.contacts.find(c => c.id === 'c1').region = '台南市東區' })
  await p.getByPlaceholder('例：朋友介紹、社團、同事').fill('社團認識'); await p.waitForTimeout(200)
  let n0 = await p.evaluate(() => window.__ops.length)
  await p.getByRole('button', { name: '儲存', exact: true }).click(); await p.waitForTimeout(900)
  let ups = await p.evaluate(n => window.__ops.slice(n).filter(o => o[0] === 'update' && o[1] === 'contacts').map(o => o[2]), n0)
  ok(ups.length === 1 && ups[0].note === '社團認識' && !('region' in ups[0]), '我改備註、另一台改地區：只寫備註，另一台的地區不被蓋掉')
  ok(await p.evaluate(() => window.__db.contacts.find(c => c.id === 'c1').region) === '台南市東區', '地區還是另一台改的「台南市東區」')
  // 兩邊改同一個欄位
  await go('/contacts/c1/edit')
  await p.evaluate(() => { window.__db.contacts.find(c => c.id === 'c1').note = '同事介紹' })
  await p.getByPlaceholder('例：朋友介紹、社團、同事').fill('教會朋友'); await p.waitForTimeout(200)
  await p.getByRole('button', { name: '儲存', exact: true }).click(); await p.waitForTimeout(700)
  let t = await text()
  ok(t.includes('這個人剛剛在另一台裝置更新過') && t.includes('另一台裝置也改了「認識管道／備註」'), '兩邊都改備註：問要用哪一份')
  await p.screenshot({ path: __dirname + '/shots/t48_conflict.png' })
  await p.getByRole('button', { name: '先看最新的' }).click(); await p.waitForTimeout(800)
  ok((await p.getByPlaceholder('例：朋友介紹、社團、同事').inputValue()) === '同事介紹' && (await text()).includes('已經換成最新的內容，你可以再改一次。'), '先看最新的：換成另一台的內容，並說明')
  await p.getByPlaceholder('例：朋友介紹、社團、同事').fill('教會朋友')
  await p.evaluate(() => { window.__db.contacts.find(c => c.id === 'c1').note = '又改了' })
  n0 = await p.evaluate(() => window.__ops.length)
  await p.getByRole('button', { name: '儲存', exact: true }).click(); await p.waitForTimeout(700)
  await p.getByRole('button', { name: '用我這次改的' }).click(); await p.waitForTimeout(800)
  ups = await p.evaluate(n => window.__ops.slice(n).filter(o => o[0] === 'update' && o[1] === 'contacts').map(o => o[2]), n0)
  ok(ups.length === 1 && ups[0].note === '教會朋友', '用我這次改的：存我的')
  console.log('ERR', JSON.stringify(errs))
  await b.close(); process.exit(fail || errs.length ? 1 : 0)
})()
