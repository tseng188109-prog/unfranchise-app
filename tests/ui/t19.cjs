const { chromium } = require('playwright')
const sheet = p => p.locator('div[style*="max-width: 520px"]').last()
;(async()=>{
  const b=await chromium.launch(); const errs=[]
  let p=await b.newPage({viewport:{width:390,height:1500}}); p.on('pageerror',e=>errs.push(e.message))
  const db = () => p.evaluate(()=>JSON.parse(JSON.stringify(window.__db)))
  await p.goto('http://127.0.0.1:8765/?y312=1'); await p.waitForTimeout(300); await p.click('#goHome'); await p.waitForTimeout(1800)
  const Y = await p.evaluate(()=>window.__add(-1))
  let d = await db(); console.log('昨天打勾（記之前）:', JSON.stringify(d.daily_checkins.filter(r=>r.date===Y&&r.task_key==='daily_3_contacts')))
  await p.getByRole('button',{name:'記一次邀約'}).first().click(); await p.waitForTimeout(400)
  let s = sheet(p); await s.getByRole('button',{name:/^昨天/}).click(); await s.getByRole('button',{name:'還在等回覆'}).click(); await s.getByRole('button',{name:'記下來'}).click(); await p.waitForTimeout(1200)
  d = await db(); console.log('昨天補記等回覆後打勾:', JSON.stringify(d.daily_checkins.filter(r=>r.date===Y&&r.task_key==='daily_3_contacts').map(r=>r.is_done)))
  await p.close()
  p=await b.newPage({viewport:{width:390,height:1500}}); p.on('pageerror',e=>errs.push(e.message))
  await p.goto('http://127.0.0.1:8765/?evwait=1'); await p.waitForTimeout(300); await p.click('#goHome'); await p.waitForTimeout(1800)
  let t = await p.textContent('#root'); console.log('活動等回覆提醒:', (t.match(/\d+\/\d+ 邀了王怡茜[^？]*？/)||[])[0])
  await p.locator('div[style*="yellow-soft"]').filter({hasText:'王怡茜'}).getByRole('button',{name:'約成了'}).click(); await p.waitForTimeout(600)
  s = sheet(p); let st = await s.textContent(); console.log('自動帶活動那天:', st.includes('見面那天就是活動那天'))
  await s.getByRole('button',{name:'記下來'}).click(); await p.waitForTimeout(1200)
  const d2 = await p.evaluate(()=>JSON.parse(JSON.stringify(window.__db)))
  console.log('結果:', JSON.stringify(d2.contact_logs.filter(l=>l.id==='ew1').map(l=>[l.kind,l.note])), JSON.stringify(d2.counter_logs.filter(r=>r.contact_id==='c1'&&r.note&&r.note.startsWith('邀請參加')).map(r=>[r.planned_date])))
  t = await p.textContent('#root'); console.log('活動底下已邀:', /王怡茜 已邀/.test(t))
  console.log('ERR', errs.slice(0,5)); await b.close()
})()
